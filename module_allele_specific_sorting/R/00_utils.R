## =========================================================================
## module_allele_specific_sorting -- shared utilities (sourced, not run)
##
## Statistics (all on the 20,807 DI25 rho05 units, 20 hybrid populations):
##
##   among-population concordance  conc_ij = cor_pops(F_i, F_j)
##       F = population x unit aquilonia-allele frequency (Fmat). Signed:
##       + = the two loci distinguish the same populations in the same ancestry
##       direction. conc_resid uses the same profiles after regressing out
##       leave-one-chromosome-out genome-wide ancestry (pp_residualize_ancestry.R).
##
##   among-population LD (Ohta-style, normalised)
##       G_i   = var_pops(F_i) / (Fbar_i (1 - Fbar_i))   (Nei-type F_ST, unweighted pops)
##       rST_ij = cov_pops(F_i, F_j) / sqrt(Fbar_i(1-Fbar_i) Fbar_j(1-Fbar_j))
##             = conc_ij * sqrt(G_i * G_j)
##       sqrt(G_i G_j) is the CEILING on among-population LD that two loci with
##       these marginal F_STs could produce if they partitioned the populations
##       identically (|conc| = 1). The ratio rST / sqrt(G_i G_j) is conc itself:
##       high F_ST produces high among-population LD only to the extent that
##       partitions are shared. This is the formal version of "high F_ST but
##       not high LD".
##
##   within-population LD  r_w_ij
##       correlation of oriented genotypes after centring each unit within each
##       population (pooled within-population correlation, sample-size
##       weighted). r_w_adj additionally regresses each unit on the individual's
##       leave-one-chromosome-out hybrid index (within-population centred), which
##       removes admixture LD generated by among-individual variation in overall
##       ancestry -- the residual is the locus-specific within-population
##       association (the classic signal of selection on unlinked conspecific
##       combinations, e.g. BDMIs).
##       Missing genotypes (2.7%) are set to 0 after centring (mean imputation);
##       this shrinks r_w slightly towards 0, identically for observed and
##       permuted data.
##
## Unit genotypes are the units' representative SNPs (best-SNP / representative,
## strictly observed calls), oriented so that dosage counts the F. aquilonia
## allele -- the same orientation as Fmat (asserted on load).
## =========================================================================
